import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync, spawn, type ChildProcess } from 'node:child_process';
import path from 'node:path';
import { stringify } from 'yaml';
import { dbPathFor } from '../db.js';

export interface LitestreamOptions {
  replicaUrl: string;
  dbPath?: string;
  retention?: string;
  syncInterval?: string;
  snapshotInterval?: string;
  validationInterval?: string;
}

export interface LitestreamCheckResult {
  installed: boolean;
  binary: string | null;
  version?: string;
  error?: string;
}

export interface LitestreamGeneration {
  generation: string;
  created: string;
}

export class LitestreamNotFoundError extends Error {
  constructor(message?: string) {
    super(
      message ??
        'litestream executable not found in PATH or $LORE_LITESTREAM_PATH.\n' +
          'Install Litestream to enable streaming SQLite replication:\n' +
          '  macOS:  brew install litestream\n' +
          '  Linux:  https://litestream.io/install\n' +
          '  Or set: export LORE_LITESTREAM_PATH=/path/to/litestream',
    );
    this.name = 'LitestreamNotFoundError';
  }
}

/**
 * Locate the litestream executable via $LORE_LITESTREAM_PATH or system PATH.
 */
export function findLitestreamBinary(): string | null {
  const envPath = process.env.LORE_LITESTREAM_PATH;
  if (envPath && existsSync(envPath)) {
    return envPath;
  }

  const lookupCmd = process.platform === 'win32' ? 'where' : 'which';
  try {
    const stdout = execFileSync(lookupCmd, ['litestream'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    if (stdout) {
      const firstLine = stdout.split(/\r?\n/)[0];
      if (firstLine && existsSync(firstLine)) return firstLine;
    }
  } catch {
    // not in path
  }

  return null;
}

/**
 * Diagnostic check verifying whether litestream is available and executable.
 */
export function checkLitestreamInstalled(): LitestreamCheckResult {
  const bin = findLitestreamBinary();
  if (!bin) {
    return {
      installed: false,
      binary: null,
      error: 'executable not found in PATH',
    };
  }

  try {
    const stdout = execFileSync(bin, ['version'], {
      encoding: 'utf8',
      timeout: 3000,
      stdio: ['ignore', 'pipe', 'pipe'],
    }).trim();
    return {
      installed: true,
      binary: bin,
      version: stdout,
    };
  } catch (err) {
    return {
      installed: false,
      binary: bin,
      error: (err as Error).message,
    };
  }
}

/**
 * Generate a standard litestream.yml configuration object and YAML text.
 */
export function generateLitestreamConfig(root: string, opts: LitestreamOptions): string {
  const targetDb = path.resolve(opts.dbPath ?? dbPathFor(root));
  const replica: Record<string, unknown> = {
    url: opts.replicaUrl,
  };
  if (opts.retention) replica['retention'] = opts.retention;
  if (opts.syncInterval) replica['sync-interval'] = opts.syncInterval;
  if (opts.snapshotInterval) replica['snapshot-interval'] = opts.snapshotInterval;
  if (opts.validationInterval) replica['validation-interval'] = opts.validationInterval;

  const doc = {
    dbs: [
      {
        path: targetDb,
        replicas: [replica],
      },
    ],
  };

  const yamlContent = stringify(doc);
  return `# Generated by Lore — streaming SQLite replication\n${yamlContent}`;
}

export function defaultLitestreamConfigPath(root: string): string {
  return path.join(root, '.lore', 'litestream.yml');
}

/**
 * Write litestream.yml configuration file into the target repository.
 */
export function writeLitestreamConfig(
  root: string,
  opts: LitestreamOptions,
  customPath?: string,
): string {
  const outPath = customPath ? path.resolve(customPath) : defaultLitestreamConfigPath(root);
  mkdirSync(path.dirname(outPath), { recursive: true });
  const content = generateLitestreamConfig(root, opts);
  writeFileSync(outPath, content, 'utf8');
  return outPath;
}

/**
 * Launch the continuous `litestream replicate` background daemon.
 */
export function spawnLitestreamReplicate(
  root: string,
  opts?: {
    configPath?: string;
    replicaUrl?: string;
    execPath?: string;
    onLog?: (line: string) => void;
    onError?: (err: Error) => void;
  },
): ChildProcess {
  const bin = opts?.execPath ?? findLitestreamBinary();
  if (!bin) throw new LitestreamNotFoundError();

  let config = opts?.configPath;
  if (!config) {
    const defaultCfg = defaultLitestreamConfigPath(root);
    if (existsSync(defaultCfg)) {
      config = defaultCfg;
    } else if (opts?.replicaUrl) {
      config = writeLitestreamConfig(root, { replicaUrl: opts.replicaUrl });
    } else {
      throw new Error(
        `No litestream config found at ${defaultCfg} and no --replica URL provided.\nRun: lore replicate config --replica <url>`,
      );
    }
  }

  const child = spawn(bin, ['replicate', '-config', config], {
    cwd: root,
    stdio: ['ignore', 'pipe', 'pipe'],
    detached: false,
  });

  child.stdout?.on('data', (chunk: Buffer) => {
    const text = chunk.toString('utf8');
    opts?.onLog?.(text);
  });

  child.stderr?.on('data', (chunk: Buffer) => {
    const text = chunk.toString('utf8');
    opts?.onLog?.(text);
  });

  child.on('error', (err) => {
    opts?.onError?.(err);
  });

  return child;
}

/**
 * Restore SQLite database from a Litestream replica snapshot + WAL segments.
 */
export async function restoreFromReplica(
  root: string,
  replicaUrl: string,
  opts?: {
    timestamp?: string;
    outputPath?: string;
    configPath?: string;
    execPath?: string;
  },
): Promise<string> {
  const bin = opts?.execPath ?? findLitestreamBinary();
  if (!bin) throw new LitestreamNotFoundError();

  const outDb = path.resolve(opts?.outputPath ?? dbPathFor(root));
  mkdirSync(path.dirname(outDb), { recursive: true });

  const args: string[] = ['restore', '-o', outDb];
  if (opts?.timestamp) {
    args.push('-timestamp', opts.timestamp);
  }
  if (opts?.configPath) {
    args.push('-config', opts.configPath);
  }
  args.push(replicaUrl);

  execFileSync(bin, args, {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });

  return outDb;
}

/**
 * Query active replica generations and snapshots from the replica.
 */
export async function listReplicaGenerations(
  root: string,
  replicaUrl?: string,
  opts?: {
    configPath?: string;
    dbPath?: string;
    execPath?: string;
  },
): Promise<LitestreamGeneration[]> {
  const bin = opts?.execPath ?? findLitestreamBinary();
  if (!bin) throw new LitestreamNotFoundError();

  const args = ['generations'];
  if (opts?.configPath) {
    args.push('-config', opts.configPath);
  }
  const target = replicaUrl ?? opts?.dbPath ?? dbPathFor(root);
  args.push(target);

  try {
    const stdout = execFileSync(bin, args, {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    }).trim();

    const lines = stdout.split(/\r?\n/).slice(1); // skip header line
    const generations: LitestreamGeneration[] = [];
    for (const line of lines) {
      const parts = line.trim().split(/\s+/);
      if (parts.length >= 2) {
        generations.push({
          generation: parts[0],
          created: parts.slice(1).join(' '),
        });
      }
    }
    return generations;
  } catch {
    return [];
  }
}
