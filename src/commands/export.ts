import { writeFileSync } from 'node:fs';
import path from 'node:path';
import pc from 'picocolors';
import { openDb, requireRoot } from '../db.js';
import { activeAt, head, type ClaimRow } from '../model.js';
import { branchFor, currentSession } from '../session.js';

export interface ExportOptions {
  md?: boolean;
  out?: string;
  session?: string;
}

function objectOf(row: ClaimRow): string {
  try {
    return String(JSON.parse(row.object_json));
  } catch {
    return row.object_json;
  }
}

/** Last meaningful segment of an entity id: `sym:src/a.ts#fn` → `fn`, `env:TOKEN` → `TOKEN`. */
function subjectName(subjectId: string): string {
  const body = subjectId.slice(subjectId.indexOf(':') + 1);
  return body.split('#').pop() ?? body;
}

function evidenceDate(e: { verified_at: string | null }): string {
  return (e.verified_at ?? '').slice(0, 10);
}

interface MdClaim {
  predicate: string;
  object: string;
  objectForSort: string;
  evidence: string;
}

/**
 * lore export --md — deterministic markdown projection of the current branch's
 * active set (SPEC §10.3). No timestamp in the output so `git diff` stays clean.
 * Sorted: subject asc → predicate asc → object asc.
 */
export function exportCommand(opts: ExportOptions): void {
  if (!opts.md) {
    throw new Error('only --md is supported for now (usage: lore export --md [--out <path>])');
  }
  const root = requireRoot();
  const db = openDb(root);
  const session = currentSession(root, opts.session);
  const branch = branchFor(session);
  const active = activeAt(db, head(db, branch) ?? head(db, 'main'));
  const stmt = db.prepare('SELECT * FROM claim WHERE id = ?');

  const bySubject = new Map<string, MdClaim[]>();
  for (const id of active.keys()) {
    const row = stmt.get(id) as ClaimRow | undefined;
    if (!row) continue;
    const list = bySubject.get(row.subject_id) ?? [];
    // Evidence comment (dim, one per row): `evidence: <kind>:<ref> @ <date>`.
    const evidence = db
      .prepare('SELECT kind, ref, verified_at FROM evidence WHERE claim_id = ? ORDER BY kind, ref')
      .all(row.id) as Array<{ kind: string; ref: string; verified_at: string | null }>;
    list.push({
      predicate: row.predicate,
      object: objectOf(row),
      // sort by the raw object text so two claims never tie
      objectForSort: objectOf(row),
      evidence: evidence
        .map((e) => `<!-- evidence: ${e.kind}:${e.ref}${evidenceDate(e) ? ` @ ${evidenceDate(e)}` : ''} -->`)
        .join('\n'),
    });
    bySubject.set(row.subject_id, list);
  }
  db.close();

  const subjects = [...bySubject.keys()].sort((a, b) => a.localeCompare(b));
  const lines: string[] = [
    '<!-- generated by lore v0.1 — do not edit, run `lore export --md` -->',
  ];
  let claimCount = 0;
  for (const subject of subjects) {
    const claims = (bySubject.get(subject) ?? []).sort((a, b) => {
      if (a.predicate !== b.predicate) return a.predicate.localeCompare(b.predicate);
      return a.objectForSort.localeCompare(b.objectForSort);
    });
    lines.push('', `## ${subjectName(subject)} (${subject})`);
    for (const c of claims) {
      claimCount++;
      lines.push(`- **${c.predicate}**: ${c.object}`);
      if (c.evidence) lines.push(...c.evidence.split('\n').map((e) => `  ${e}`));
    }
  }

  const md = `${lines.join('\n')}\n`;

  if (opts.out) {
    const out = path.resolve(opts.out);
    writeFileSync(out, md);
    console.log(`wrote ${out} ${pc.dim(`(${subjects.length} subjects, ${claimCount} claims)`)}`);
    return;
  }
  process.stdout.write(md);
}
