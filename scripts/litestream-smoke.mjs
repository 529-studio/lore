#!/usr/bin/env node
// Smoke test for Litestream SQLite streaming replication subsystem
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { chmodSync, existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import {
  checkLitestreamInstalled,
  defaultLitestreamConfigPath,
  generateLitestreamConfig,
  listReplicaGenerations,
  restoreFromReplica,
  spawnLitestreamReplicate,
  writeLitestreamConfig,
} from '../dist/sync/litestream.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLI = path.join(ROOT, 'dist', 'cli.js');
const work = mkdtempSync(path.join(tmpdir(), 'lore-litestream-'));

function lore(args, env = {}) {
  const result = spawnSync(process.execPath, [CLI, ...args], {
    cwd: work,
    encoding: 'utf8',
    env: { ...process.env, ...env },
  });
  return result;
}

// 1. Test standalone YAML config generation
const configYaml = generateLitestreamConfig('/tmp/demo-lore', {
  replicaUrl: 's3://my-bucket/lore.db',
  retention: '48h',
  syncInterval: '2s',
  snapshotInterval: '6h',
});
assert.match(configYaml, /Generated by Lore/);
const parsed = parse(configYaml);
assert.equal(parsed.dbs[0].path, path.resolve('/tmp/demo-lore/.lore/lore.db'));
assert.equal(parsed.dbs[0].replicas[0].url, 's3://my-bucket/lore.db');
assert.equal(parsed.dbs[0].replicas[0].retention, '48h');
assert.equal(parsed.dbs[0].replicas[0]['sync-interval'], '2s');
assert.equal(parsed.dbs[0].replicas[0]['snapshot-interval'], '6h');
console.log('[OK] litestream config generation passed');

// 2. Test writing config file
const writtenPath = writeLitestreamConfig(work, {
  replicaUrl: 'file:///shared/replicas/lore.db',
});
assert.equal(writtenPath, defaultLitestreamConfigPath(work));
assert.equal(existsSync(writtenPath), true);
console.log('[OK] writeLitestreamConfig passed');

// 3. Test CLI init and replicate config command
const initRes = lore(['init']);
assert.equal(initRes.status, 0);

const cfgRes = lore(['replicate', 'config', '--replica', 's3://company-vault/lore-sync.db', '--retention', '72h']);
assert.equal(cfgRes.status, 0);
assert.match(cfgRes.stdout, /wrote Litestream configuration/);

const cfgFile = readFileSync(defaultLitestreamConfigPath(work), 'utf8');
assert.match(cfgFile, /s3:\/\/company-vault\/lore-sync\.db/);
assert.match(cfgFile, /retention: 72h/);

const loreCfg = JSON.parse(readFileSync(path.join(work, '.lore', 'config.json'), 'utf8'));
assert.equal(loreCfg.litestream?.replica_url, 's3://company-vault/lore-sync.db');
console.log('[OK] lore replicate config command passed');

// 4. Test CLI status when litestream is not installed
const statusRes = lore(['replicate', 'status'], { LORE_LITESTREAM_PATH: '/nonexistent/litestream' });
assert.equal(statusRes.status, 0);
assert.match(statusRes.stdout, /Litestream Streaming Replication Status:/);
assert.match(statusRes.stdout, /s3:\/\/company-vault\/lore-sync\.db/);
console.log('[OK] lore replicate status passed');

// 5. Test mock litestream executable to verify full runtime workflow
const mockBinPath = path.join(work, 'mock-litestream');
const mockScript = `#!/usr/bin/env bash
if [ "$1" = "version" ]; then
  echo "litestream v0.3.13"
  exit 0
fi
if [ "$1" = "generations" ]; then
  echo "generation  created"
  echo "gen_abc123  2026-11-17T10:00:00Z"
  exit 0
fi
if [ "$1" = "restore" ]; then
  touch "$3"
  echo "restored database to $3"
  exit 0
fi
if [ "$1" = "replicate" ]; then
  echo "litestream: replication started successfully"
  exit 0
fi
exit 0
`;
writeFileSync(mockBinPath, mockScript, 'utf8');
chmodSync(mockBinPath, 0o755);

// Verify checkLitestreamInstalled with mock binary
process.env.LORE_LITESTREAM_PATH = mockBinPath;
const checkRes = checkLitestreamInstalled();
assert.equal(checkRes.installed, true);
assert.equal(checkRes.version, 'litestream v0.3.13');
assert.equal(checkRes.binary, mockBinPath);

// Verify CLI replicate check with mock binary
const checkCli = lore(['replicate', 'check'], { LORE_LITESTREAM_PATH: mockBinPath });
assert.equal(checkCli.status, 0);
assert.match(checkCli.stdout, /litestream binary found/);
assert.match(checkCli.stdout, /v0\.3\.13/);
console.log('[OK] mock litestream detection and check command passed');

// Verify listReplicaGenerations
const gens = await listReplicaGenerations(work, 's3://company-vault/lore-sync.db', { execPath: mockBinPath });
assert.equal(gens.length, 1);
assert.equal(gens[0].generation, 'gen_abc123');
console.log('[OK] mock replica generations list passed');

// Verify restoreFromReplica
const testRestoreTarget = path.join(work, 'restored.db');
const restoredPath = await restoreFromReplica(work, 's3://company-vault/lore-sync.db', {
  outputPath: testRestoreTarget,
  execPath: mockBinPath,
});
assert.equal(restoredPath, testRestoreTarget);
assert.equal(existsSync(testRestoreTarget), true);
console.log('[OK] mock restoreFromReplica passed');

// Verify spawnLitestreamReplicate
let loggedText = '';
const child = spawnLitestreamReplicate(work, {
  execPath: mockBinPath,
  onLog: (txt) => {
    loggedText += txt;
  },
});
await new Promise((resolve) => child.on('exit', resolve));
assert.match(loggedText, /replication started successfully/);
console.log('[OK] mock spawnLitestreamReplicate passed');

console.log('[OK] all litestream streaming replication tests passed');
